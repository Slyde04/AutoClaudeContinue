def _config_dict(config: Config) -> dict[str, Any]:
    return asdict(config)


class EventHub:
    """Keeps a snapshot for new windows and fans events out to SSE clients."""

    def __init__(self, store: ConfigStore) -> None:
        self.store = store
        self._lock = threading.Lock()
        self._clients: set[queue.Queue] = set()
        self._state = dict(STATE_STARTING)
        self._activity: deque[dict[str, Any]] = deque(maxlen=ACTIVITY_LIMIT)
        self._chats: list[str] = []
        self._chat_app = ""
        self._chat_app_label = ""
        self._sequence = 0

    # -- subscriptions -------------------------------------------------

    def subscribe(self) -> queue.Queue:
        client: queue.Queue = queue.Queue(maxsize=1000)
        with self._lock:
            self._clients.add(client)
            snapshot = self._snapshot_locked()
        client.put_nowait({"type": "hello", "snapshot": snapshot})
        return client

    def unsubscribe(self, client: queue.Queue) -> None:
        with self._lock:
            self._clients.discard(client)

    def publish(self, event: dict[str, Any]) -> None:
        if not event:
            return
        with self._lock:
            self._sequence += 1
            event.setdefault("seq", self._sequence)
            kind = event.get("type")
            if kind == "state":
                self._state = dict(event)
            elif kind == "chats":
                self._chats = list(event.get("chats") or [])
                self._chat_app = str(event.get("app") or "")
                self._chat_app_label = str(event.get("app_label") or "")
            elif kind == "log":
                self._activity.append(
                    {
                        "time": time.strftime("%H:%M"),
                        "message": str(event.get("message") or ""),
                        "level": str(event.get("level") or "info"),
                    }
                )
            for client in list(self._clients):
                try:
                    client.put_nowait(event)
                except queue.Full:
                    try:
                        client.get_nowait()
                    except queue.Empty:
                        pass
                    try:
                        client.put_nowait(event)
                    except queue.Full:
                        pass

    def log(self, message: str, level: str = "info") -> None:
        if not message:
            return
        log.info(message)
        self.publish({"type": "log", "message": message, "level": level})

    def config_changed(self, config: Config | None = None) -> None:
        current = config or self.store.get()
        self.publish({"type": "config", "config": _config_dict(current)})

    # -- snapshot ------------------------------------------------------

    def snapshot(self) -> dict[str, Any]:
        with self._lock:
            return self._snapshot_locked()

    def _snapshot_locked(self) -> dict[str, Any]:
        return {
            "version": __version__,
            "config": _config_dict(self.store.get()),
            "state": dict(self._state),
            "activity": list(self._activity),
            "chats": list(self._chats),
            "chat_app": self._chat_app,
            "chat_app_label": self._chat_app_label,
            "data_dir": str(default_data_dir()),
            "license_available": license_path() is not None,
        }


class Backend:
    def __init__(self, store: ConfigStore) -> None:
        self.store = store
        self.events: queue.Queue = queue.Queue()
        self.automator = Automator(store, self.events)
        self.hub = EventHub(store)
        self._stop = threading.Event()
        self._bridge: threading.Thread | None = None
        self._server: ThreadingHTTPServer | None = None

    # -- lifecycle -----------------------------------------------------

    def attach_server(self, server: ThreadingHTTPServer) -> None:
        self._server = server

    def start(self) -> None:
        self.hub.config_changed(self.store.get())
        self.automator.start()
        self._bridge = threading.Thread(
            target=self._pump_events,
            name="acc-event-bridge",
            daemon=True,
        )
        self._bridge.start()

    def stop(self) -> None:
        if self._stop.is_set():
            return
        self._stop.set()
        try:
            self.automator.stop()
            self.automator.join(timeout=3.0)
        except Exception:
            log.debug("Could not stop the automator cleanly", exc_info=True)
        if self._bridge is not None:
            self._bridge.join(timeout=1.0)
        server = self._server
        if server is not None:
            threading.Thread(target=server.shutdown, daemon=True).start()

    def _pump_events(self) -> None:
        while not self._stop.is_set():
            try:
                event = self.events.get(timeout=0.25)
            except queue.Empty:
                continue
            try:
                kind = event.get("type")
                if kind == "dev_mode":
                    self.hub.config_changed(self.store.get())
                elif kind == "draft_reset":
                    self.hub.config_changed(self.store.get())
                self.hub.publish(event)
            except Exception:
                log.exception("Could not publish %r", event)

    # -- config / actions ---------------------------------------------

    def update_config(self, changes: dict[str, Any]) -> Config:
        allowed = {field.name for field in fields(Config)}
        clean = {key: value for key, value in changes.items() if key in allowed}
        config = self.store.update(**clean)
        self.hub.config_changed(config)
        self.automator.submit("config_changed")
        return config

    def add_attachments(self, paths: list[str]) -> dict[str, Any]:
        current = list(self.store.get().attachments)
        added = 0
        skipped = 0
        for raw in paths:
            path = str(raw)
            if not path or not is_image(path) or not Path(path).is_file():
                skipped += 1
                continue
            if path in current:
                continue
            if len(current) >= MAX_ATTACHMENTS:
                skipped += 1
                continue
            current.append(path)
            added += 1
        self.update_config({"attachments": tuple(current)})
        message = ""
        if added:
            message = f"{added} image{'s' if added != 1 else ''} attached."
            if skipped:
                message += f" {skipped} skipped."
            self.hub.log(message)
        elif skipped:
            message = "No new images added."
        return {
            "added": added,
            "skipped": skipped,
            "message": message,
            "attachments": current,
        }

    def remove_attachment(self, path: str) -> dict[str, Any]:
        current = [item for item in self.store.get().attachments if item != path]
        self.update_config({"attachments": tuple(current)})
        self.hub.log("Image removed.")
        return {"attachments": current}

    def paste_attachments(self) -> dict[str, Any]:
        paths = save_clipboard_images()
        if not paths:
            return {
                "added": 0,
                "skipped": 0,
                "message": "No image found on the clipboard.",
                "attachments": list(self.store.get().attachments),
            }
        return self.add_attachments(paths)

    def send_now(self, message: str | None = None) -> Config:
        if isinstance(message, str) and message.strip():
            self.update_config({"message": message.strip()})
        self.automator.submit("check_now")
        self.hub.log("Manual message send requested.")
        return self.store.get()


class ApiHandler(BaseHTTPRequestHandler):
    backend: Backend
    token: str = ""
    ui_dir: Path | None = None

    server_version = f"AutoClaudeContinue/{__version__}"
    protocol_version = "HTTP/1.1"

    # -- plumbing ------------------------------------------------------

    def log_message(self, fmt: str, *args) -> None:
        log.debug("HTTP %s - %s", self.address_string(), fmt % args)

    def do_OPTIONS(self) -> None:  # noqa: N802
        self.send_response(HTTPStatus.NO_CONTENT)
        self._cors()
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type, X-ACC-Token")
        self.send_header("Content-Length", "0")
        self.end_headers()

    def do_GET(self) -> None:  # noqa: N802
        parsed = urlparse(self.path)
        if parsed.path.startswith("/api/"):
            if not self._authorized(parsed):
                self._json({"error": "unauthorized"}, HTTPStatus.UNAUTHORIZED)
                return
        try:
            if parsed.path == "/api/health":
                self._json(
                    {
                        "ok": True,
                        "version": __version__,
                        "state": self.backend.hub.snapshot()["state"]["state"],
                    }
                )
            elif parsed.path == "/api/bootstrap":
                self._json(self.backend.hub.snapshot())
            elif parsed.path == "/api/events":
                self._events()
            elif parsed.path == "/api/license":
                self._send_text(self._license_text())
            elif parsed.path == "/api/attachment-thumb":
                self._thumbnail(parsed)
            else:
                self._serve_ui(parsed.path)
        except (BrokenPipeError, ConnectionResetError):
            pass
        except Exception:
            log.exception("GET %s failed", self.path)
            try:
                self._json({"error": "internal error"}, HTTPStatus.INTERNAL_SERVER_ERROR)
            except Exception:
                pass

    def do_POST(self) -> None:  # noqa: N802
        parsed = urlparse(self.path)
        if not self._authorized(parsed):
            self._json({"error": "unauthorized"}, HTTPStatus.UNAUTHORIZED)
            return
        try:
            body = self._read_json()
            path = parsed.path
            if path == "/api/config":
                config = self.backend.update_config(body)
                self._json({"ok": True, "config": _config_dict(config)})
            elif path == "/api/detection":
                config = self.backend.update_config(
                    {"detection_enabled": bool(body.get("enabled"))}
                )
                self.backend.hub.log(
                    "Detection resumed." if config.detection_enabled else "Detection paused."
                )
                self._json({"ok": True, "config": _config_dict(config)})
            elif path == "/api/send":
                config = self.backend.send_now(body.get("message"))
                self._json({"ok": True, "config": _config_dict(config)})
            elif path == "/api/chats/refresh":
                self.backend.automator.submit("refresh_chats")
                self._json({"ok": True})
            elif path == "/api/attachments":
                action = str(body.get("action") or "add")
                if action == "paste":
                    result = self.backend.paste_attachments()
                elif action == "remove":
                    result = self.backend.remove_attachment(str(body.get("path") or ""))
                else:
                    paths = body.get("paths") or []
                    result = self.backend.add_attachments(
                        [str(item) for item in paths if str(item).strip()]
                    )
                self._json({"ok": True, **result})
            elif path == "/api/open":
                target = str(body.get("target") or "data")
                self._open_target(target)
                self._json({"ok": True})
            elif path == "/api/open-url":
                url = str(body.get("url") or "").strip()
                if not url.lower().startswith(("http://", "https://")):
                    self._json({"error": "invalid url"}, HTTPStatus.BAD_REQUEST)
                    return
                webbrowser.open(url)
                self._json({"ok": True})
            elif path == "/api/shutdown":
                self._json({"ok": True})
                threading.Thread(target=self.backend.stop, daemon=True).start()
            else:
                self._json({"error": "not found"}, HTTPStatus.NOT_FOUND)
        except ValueError as exc:
            self._json({"error": str(exc)}, HTTPStatus.BAD_REQUEST)
        except Exception as exc:
            log.exception("POST %s failed", self.path)
            try:
                self._json({"error": str(exc)}, HTTPStatus.INTERNAL_SERVER_ERROR)
            except Exception:
                pass

    # -- auth / responses ---------------------------------------------

    def _authorized(self, parsed) -> bool:
        if not self.token:
            return True
        supplied = self.headers.get("X-ACC-Token", "")
        if not supplied:
            supplied = parse_qs(parsed.query).get("token", [""])[0]
        return supplied == self.token

    def _cors(self) -> None:
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Private-Network", "true")
        self.send_header("Vary", "Origin")

    def _json(self, payload: Any, status: HTTPStatus = HTTPStatus.OK) -> None:
        data = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        try:
            self.send_response(status)
            self._cors()
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Cache-Control", "no-store")
            self.send_header("Content-Length", str(len(data)))
            self.end_headers()
            self.wfile.write(data)
        except (BrokenPipeError, ConnectionResetError):
            # The client can close the socket before reading the whole
            # response (the shell does this during shutdown).
            pass

    def _send_text(self, text: str, status: HTTPStatus = HTTPStatus.OK) -> None:
        data = text.encode("utf-8")
        try:
            self.send_response(status)
            self._cors()
            self.send_header("Content-Type", "text/plain; charset=utf-8")
            self.send_header("Cache-Control", "no-store")
            self.send_header("Content-Length", str(len(data)))
            self.end_headers()
            self.wfile.write(data)
        except (BrokenPipeError, ConnectionResetError):
            pass

    def _read_json(self) -> dict[str, Any]:
        try:
            length = int(self.headers.get("Content-Length") or "0")
        except ValueError:
            raise ValueError("Invalid content length") from None
        if length <= 0:
            return {}
        if length > MAX_BODY_BYTES:
            raise ValueError("Request body is too large")
        raw = self.rfile.read(length)
        if not raw:
            return {}
        try:
            payload = json.loads(raw.decode("utf-8"))
        except (UnicodeDecodeError, ValueError):
            raise ValueError("Invalid JSON") from None
        if not isinstance(payload, dict):
            raise ValueError("Expected a JSON object")
        return payload

    # -- SSE -----------------------------------------------------------

    def _events(self) -> None:
        client = self.backend.hub.subscribe()
        self.send_response(HTTPStatus.OK)
        self._cors()
        self.send_header("Content-Type", "text/event-stream; charset=utf-8")
        self.send_header("Cache-Control", "no-cache, no-transform")
        self.send_header("Connection", "keep-alive")
        self.send_header("X-Accel-Buffering", "no")
        self.end_headers()
        self.close_connection = True
        last_ping = time.monotonic()
        try:
            while True:
                try:
                    event = client.get(timeout=5.0)
                except queue.Empty:
                    if time.monotonic() - last_ping >= 15.0:
                        self.wfile.write(b": ping\n\n")
                        self.wfile.flush()
                        last_ping = time.monotonic()
                    continue
                payload = json.dumps(event, ensure_ascii=False)
                kind = str(event.get("type") or "message")
                self.wfile.write(
                    f"event: {kind}\ndata: {payload}\n\n".encode("utf-8")
                )
                self.wfile.flush()
                last_ping = time.monotonic()
        except (BrokenPipeError, ConnectionResetError, OSError):
            pass
        finally:
            self.backend.hub.unsubscribe(client)

    # -- static preview ------------------------------------------------

    def _serve_ui(self, path: str) -> None:
        ui_dir = self.ui_dir
        if ui_dir is None:
            self._json({"error": "not found"}, HTTPStatus.NOT_FOUND)
            return
        relative = unquote(path).lstrip("/") or "index.html"
        target = (ui_dir / relative).resolve()
        try:
            target.relative_to(ui_dir.resolve())
        except ValueError:
            self._json({"error": "not found"}, HTTPStatus.NOT_FOUND)
            return
        if not target.is_file():
            self._json({"error": "not found"}, HTTPStatus.NOT_FOUND)
            return
        content_types = {
            ".html": "text/html; charset=utf-8",
            ".css": "text/css; charset=utf-8",
            ".js": "text/javascript; charset=utf-8",
            ".svg": "image/svg+xml",
            ".png": "image/png",
            ".jpg": "image/jpeg",
            ".jpeg": "image/jpeg",
            ".woff2": "font/woff2",
            ".ttf": "font/ttf",
            ".ico": "image/x-icon",
        }
        data = target.read_bytes()
        try:
            self.send_response(HTTPStatus.OK)
            self._cors()
            self.send_header(
                "Content-Type",
                content_types.get(target.suffix.lower(), "application/octet-stream"),
            )
            self.send_header("Cache-Control", "no-cache")
            self.send_header("Content-Length", str(len(data)))
            self.end_headers()
            self.wfile.write(data)
        except (BrokenPipeError, ConnectionResetError):
            pass

    # -- misc ----------------------------------------------------------

    def _thumbnail(self, parsed) -> None:
        raw = parse_qs(parsed.query).get("path", [""])[0]
        path = Path(unquote(raw)).resolve()
        allowed = {
            str(Path(item).resolve()).lower()
            for item in self.backend.store.get().attachments
        }
        if str(path).lower() not in allowed:
            self._json({"error": "not found"}, HTTPStatus.NOT_FOUND)
            return
        try:
            from PIL import Image

            with Image.open(path) as image:
                image = image.convert("RGBA")
                image.thumbnail((72, 72), Image.Resampling.LANCZOS)
                buffer = BytesIO()
                image.save(buffer, format="PNG")
            data = buffer.getvalue()
        except Exception:
            log.debug("Could not render thumbnail for %s", path, exc_info=True)
            self._json({"error": "not found"}, HTTPStatus.NOT_FOUND)
            return
        try:
            self.send_response(HTTPStatus.OK)
            self._cors()
            self.send_header("Content-Type", "image/png")
            self.send_header("Cache-Control", "no-cache")
            self.send_header("Content-Length", str(len(data)))
            self.end_headers()
            self.wfile.write(data)
        except (BrokenPipeError, ConnectionResetError):
            pass

    def _open_target(self, target: str) -> None:
        if target == "log":
            path = default_data_dir() / "app.log"
        elif target == "license":
            path = license_path()
        else:
            path = default_data_dir()
        if path is None:
            raise ValueError("That file is not available")
        if path.exists() or path.suffix == "":
            os.startfile(str(path))  # type: ignore[attr-defined]
        else:
            raise ValueError(f"Not found: {path}")

    @staticmethod
    def _license_text() -> str:
        path = license_path()
        if path is None:
            return LICENSE_FALLBACK
        try:
            return path.read_text(encoding="utf-8")
        except (OSError, UnicodeError):
            return LICENSE_FALLBACK


def _watch_parent(backend: Backend) -> None:
    """Stop the backend if the desktop shell disappears unexpectedly."""

    if os.name != "nt":
        return
    try:
        parent = int(os.environ.get("ACC_PARENT_PID", ""))
    except (TypeError, ValueError):
        return
    if parent <= 0:
        return

    import ctypes
    from ctypes import wintypes

    synchronize = 0x00100000
    kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
    kernel32.OpenProcess.argtypes = [wintypes.DWORD, wintypes.BOOL, wintypes.DWORD]
    kernel32.OpenProcess.restype = wintypes.HANDLE
    kernel32.WaitForSingleObject.argtypes = [wintypes.HANDLE, wintypes.DWORD]
    kernel32.WaitForSingleObject.restype = wintypes.DWORD
    kernel32.CloseHandle.argtypes = [wintypes.HANDLE]
    kernel32.CloseHandle.restype = wintypes.BOOL

    handle = kernel32.OpenProcess(synchronize, False, parent)
    if not handle:
        return
    try:
        while kernel32.WaitForSingleObject(handle, 1000) == 0x00000102:
            pass
    finally:
        kernel32.CloseHandle(handle)
    log.info("The desktop shell exited; stopping the backend")
    backend.stop()


def _bind_server(port: int, handler: type[ApiHandler]) -> ThreadingHTTPServer:
    class QuietServer(ThreadingHTTPServer):
        daemon_threads = True

        def handle_error(self, request, client_address) -> None:
            error = sys.exc_info()[1]
            if isinstance(error, (BrokenPipeError, ConnectionResetError)):
                return
            super().handle_error(request, client_address)

    return QuietServer(("127.0.0.1", port), handler)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="AutoClaudeContinue background API")
    parser.add_argument("--port", type=int, default=int(os.environ.get("ACC_PORT", "47823")))
    parser.add_argument("--token", default=os.environ.get("ACC_API_TOKEN", ""))
    parser.add_argument("--ui-dir", default=os.environ.get("ACC_UI_DIR", ""))
    parser.add_argument("--no-token", action="store_true")
    args = parser.parse_args(argv)

    setup_logging()
    log.info("Starting AutoClaudeContinue backend %s", __version__)
    store = ConfigStore()
    backend = Backend(store)
    handler = type(
        "BoundApiHandler",
        (ApiHandler,),
        {
            "backend": backend,
            "token": "" if args.no_token else args.token,
            "ui_dir": Path(args.ui_dir).resolve() if args.ui_dir else None,
        },
    )
    try:
        server = _bind_server(args.port, handler)
    except OSError:
        log.exception("Could not listen on 127.0.0.1:%s", args.port)
        return 1
    backend.attach_server(server)
    backend.start()
    threading.Thread(
        target=_watch_parent,
        args=(backend,),
        name="acc-parent-watch",
        daemon=True,
    ).start()
    log.info("API listening on http://127.0.0.1:%s", args.port)

    def stop(_signum=None, _frame=None):
        backend.stop()

    try:
        signal.signal(signal.SIGTERM, stop)
        signal.signal(signal.SIGINT, stop)
    except (ValueError, OSError):
        pass

    try:
        server.serve_forever(poll_interval=0.25)
    except KeyboardInterrupt:
        pass
    finally:
        backend.stop()
        server.server_close()
        log.info("Backend stopped")
    return 0
if __name__ == "__main__":
    raise SystemExit(main())
