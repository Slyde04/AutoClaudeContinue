"""Local HTTP API used by the Tauri desktop shell.

The UI is a web page, so the Python worker exposes a tiny JSON/SSE service on
loopback.  A random token is generated by the Tauri shell and passed in
``ACC_API_TOKEN``; requests without it are refused unless the backend was
started explicitly with an empty token (useful for browser previews).
"""

